import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const webRoot = path.join(repoRoot, 'web');
const outputFile = path.join(repoRoot, 'android', 'local-app-shell.ts');
const html = await readFile(path.join(webRoot, 'index.html'), 'utf8');
const scriptMatch = html.match(/<script\s+type="module">([\s\S]*?)<\/script>/u);
if (!scriptMatch) throw new Error('Could not find the app module script in web/index.html');

const wasmBinary = await readFile(path.join(webRoot, 'vendor', 'ort-wasm-simd-threaded.wasm'));
const wasmModule = await readFile(path.join(webRoot, 'vendor', 'ort-wasm-simd-threaded.mjs'));
let appSource = scriptMatch[1];
const wasmPathLine = "ort.env.wasm.wasmPaths = new URL('./vendor/', document.baseURI).href;";
if (!appSource.includes(wasmPathLine)) throw new Error('Could not locate the ONNX Runtime wasm path assignment');
appSource = appSource.replace(
  wasmPathLine,
  `ort.env.wasm.wasmBinary = Uint8Array.from(atob('${wasmBinary.toString('base64')}'), (c) => c.charCodeAt(0));\n` +
    `ort.env.wasm.wasmPaths = { mjs: 'data:text/javascript;base64,${wasmModule.toString('base64')}' };`,
);
appSource = appSource.replace("ort.env.wasm.proxy = params.get('proxy') !== '0';", 'ort.env.wasm.proxy = false;');
appSource = appSource.replace(
  "if ('serviceWorker' in navigator && location.protocol !== 'file:' && params.get('sw') !== '0') {",
  "if (false && 'serviceWorker' in navigator && location.protocol !== 'file:' && params.get('sw') !== '0') {",
);

const bundled = await build({
  stdin: {
    contents: appSource,
    resolveDir: webRoot,
    sourcefile: 'sayit-apk-entry.mjs',
    loader: 'js',
  },
  bundle: true,
  format: 'esm',
  platform: 'browser',
  target: 'es2022',
  minify: true,
  write: false,
});
if (bundled.outputFiles.length !== 1) throw new Error('Expected one self-contained app JavaScript bundle');

const scriptTag = `<script type="module">${bundled.outputFiles[0].text}</script>`;
const appHtml = html.replace(scriptMatch[0], scriptTag);
const serializedHtml = JSON.stringify(appHtml);
await writeFile(
  outputFile,
  `// Generated by scripts/prepare-local-web.mjs. Do not edit by hand.\n` +
    `export const LOCAL_APP_BASE_URL = 'https://sayit.local/';\n` +
    `export const LOCAL_APP_HTML = ${serializedHtml};\n`,
);
console.log(`Generated APK-local application shell: ${path.relative(repoRoot, outputFile)} (${Buffer.byteLength(appHtml)} bytes HTML)`);
